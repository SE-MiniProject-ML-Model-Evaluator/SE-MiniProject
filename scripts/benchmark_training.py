#!/usr/bin/env python
"""NFR-02 / TC-13: time every catalogue model on a 10,000 x 20 dataset (target: <= 60 s each).

Usage (from the repo root, with the virtual environment active):
    py scripts/benchmark_training.py
Writes docs/test_results/performance_training.md
"""
import os
import pathlib
import platform
import sys
import tempfile
import time

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
os.environ.setdefault("DJANGO_SETTINGS_MODULE", "mlme.settings")

LIMIT_S = 60
ROWS, FEATURES = 10_000, 20


def make_frames():
    import pandas as pd
    from sklearn.datasets import make_classification, make_regression
    Xc, yc = make_classification(n_samples=ROWS, n_features=FEATURES, n_informative=10, n_classes=3,
                                 random_state=42)
    cls = pd.DataFrame(Xc, columns=[f"f{i}" for i in range(FEATURES)])
    cls["label"] = [f"class_{v}" for v in yc]
    Xr, yr = make_regression(n_samples=ROWS, n_features=FEATURES, noise=10.0, random_state=42)
    reg = pd.DataFrame(Xr, columns=[f"f{i}" for i in range(FEATURES)])
    reg["value"] = yr
    return {"classification": (cls, "label"), "regression": (reg, "value")}


def run_benchmark(use_test_db=False):
    """Return a list of (task, model label, seconds, status). Works inside pytest or standalone."""
    import django
    if not use_test_db:
        django.setup()
        from django.conf import settings
        from django.db import connection
        settings.MLME_SYNC_JOBS = True
        settings.MEDIA_ROOT = pathlib.Path(tempfile.mkdtemp(prefix="mlme-bench-"))
        old_name = connection.creation.create_test_db(verbosity=0, keepdb=False)
    from django.contrib.auth import get_user_model
    from django.core.files.uploadedfile import SimpleUploadedFile

    from datasets.config import save_config
    from datasets.services import store_dataset
    from mlengine.catalogue import models_for
    from mlengine.jobs import start_evaluations

    user, _ = get_user_model().objects.get_or_create(username="bench@test.com", defaults={"email": "bench@test.com"})
    results = []
    try:
        for task, (frame, target) in make_frames().items():
            upload = SimpleUploadedFile(f"bench_{task}.csv", frame.to_csv(index=False).encode(),
                                        content_type="text/csv")
            dataset = store_dataset(user, upload)
            save_config(dataset, {"target": target, "features": [c for c in frame.columns if c != target],
                                  "missing_strategy": "none", "test_size": 20, "random_seed": 42})
            dataset.refresh_from_db()
            for key, spec in models_for(task).items():
                started = time.monotonic()
                _, (evaluation,) = start_evaluations(user, dataset, [key])
                evaluation.refresh_from_db()
                seconds = round(time.monotonic() - started, 2)
                results.append((task, spec["label"], seconds, evaluation.status))
                print(f"  {task:<15} {spec['label']:<26} {seconds:>7.2f} s  {evaluation.status}", flush=True)
    finally:
        if not use_test_db:
            connection.creation.destroy_test_db(old_name, verbosity=0)
    return results


def write_report(results):
    out = ROOT / "docs" / "test_results" / "performance_training.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    passed = all(s <= LIMIT_S and st == "completed" for _, _, s, st in results)
    lines = [
        "# NFR-02 training time (TC-13 step 2)", "",
        f"Generated by `scripts/benchmark_training.py` on {time.strftime('%d %b %Y %H:%M')}.", "",
        f"- Machine: {platform.platform()}, Python {platform.python_version()}, {os.cpu_count()} CPU threads",
        f"- Dataset: synthetic, {ROWS:,} rows x {FEATURES} features (80/20 split), default hyperparameters",
        f"- Target: each model trains and evaluates in **{LIMIT_S} s or less**", "",
        "| Task | Model | Time (s) | Status | Result |", "|---|---|---|---|---|",
    ]
    for task, label, seconds, status in results:
        ok = "✅ pass" if seconds <= LIMIT_S and status == "completed" else "❌ fail"
        lines.append(f"| {task} | {label} | {seconds:.2f} | {status} | {ok} |")
    lines += ["", f"**Overall: {'PASS' if passed else 'FAIL'}** (slowest: {max(r[2] for r in results):.2f} s)", ""]
    out.write_text("\n".join(lines), encoding="utf-8")
    return out, passed


if __name__ == "__main__":
    print(f"Training every catalogue model on {ROWS:,} x {FEATURES} (limit {LIMIT_S} s each)...")
    path, ok = write_report(run_benchmark())
    print(f"\nWrote {path.relative_to(ROOT)} - overall {'PASS' if ok else 'FAIL'}")
    sys.exit(0 if ok else 1)
